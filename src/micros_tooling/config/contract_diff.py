"""Review declaration semantics against Git, without an acknowledgment file."""
import copy
import io
import json
from pathlib import Path
import subprocess
import tarfile
import tempfile

from micros_tooling.storage.packages import require, canonical_schema, digest


def service_view(path):
    from micros_tooling.config.declarations import contract
    from micros_tooling.config.service_generation import definition
    from micros_tooling.config.service_hooks import hooks, signature, starter
    model = contract(path)
    _, _, api, _, ports, commands = definition(path, model)
    view = copy.deepcopy(model)
    for direction in ('subscriptions', 'publications'):
        for port in view[direction].values():
            port['schema'] = digest(canonical_schema(Path(port['schema']).read_bytes()))
            port.pop('_reference', None)
    # The declaration's spelling and reference paths are not semantic changes.
    view.pop('_type_refs', None)
    hook_signatures = {}
    stubs = {}
    if model['build'].get('lifecycle') == 'hooks':
        refs = model['_type_refs']['commands']
        hook_signatures = {n: signature(n, p) for n, p, _ in hooks(api, ports, commands, refs)}
        full = starter(api, ports, commands, refs)
        # Hook bodies are generated by this module, not parsed from user C.
        for block in full.split('/**')[1:]:
            for name in hook_signatures:
                if hook_signatures[name] + '\n{' in block:
                    stubs[name] = '/**' + block
                    break
    return view, hook_signatures, stubs


def unit_view(path):
    from micros_tooling.config.configuration import load_project
    recipe = load_project(path)
    services = {}
    for service in recipe['services']:
        spec = service.get('_configuration')
        services[service['name']] = dict(
            version=service['version'], memory={k:service[k] for k in ('arena', 'stack_bytes')},
            settings=spec['values'] if spec else {},
            configuration_schema=spec['definition'] if spec else {},
            gpio=service['_interface']['gpio'], channels=service['channels'],
            exposure=service.get('_commands', {}).get('exposed', []))
    return dict(board=recipe['board'], services=services, required_sdkconfig=recipe['required_sdkconfig']), {}, {}


def changes(before, after, prefix=''):
    if isinstance(before, dict) and isinstance(after, dict):
        return [change for key in sorted(before.keys() | after.keys())
                for change in changes(before.get(key), after.get(key), f'{prefix}.{key}' if prefix else key)]
    if before == after: return []
    return [dict(path=prefix, before=before, after=after)]


def compare(path, base):
    path = Path(path).resolve()
    if path.is_dir(): path /= 'service.toml'
    require(path.is_file(), f'Declaration not found: {path}')
    root = Path(subprocess.check_output(['git', '-C', str(path.parent), 'rev-parse', '--show-toplevel'], text=True).strip())
    revision = subprocess.check_output(['git', '-C', str(root), 'rev-parse', '--verify', base + '^{commit}'], text=True).strip()
    relative = path.relative_to(root)
    from micros_tooling.config.configuration import read_toml
    is_unit = 'unit' in read_toml(path)
    inspect = unit_view if is_unit else service_view
    current, current_hooks, stubs = inspect(path)
    archive = subprocess.check_output(['git', '-C', str(root), 'archive', revision])
    with tempfile.TemporaryDirectory(prefix='micros-contract-diff-') as temporary:
        snapshot = Path(temporary).resolve()
        with tarfile.open(fileobj=io.BytesIO(archive)) as tree:
            for member in tree.getmembers():
                if not member.isfile(): continue
                destination = snapshot / member.name
                require(destination.resolve().is_relative_to(snapshot), 'Invalid Git archive path')
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(tree.extractfile(member).read())
        # The ignored dependency link is external to the application's Git tree.
        # Resolve it against this invocation's pinned SDK; never use private state.
        dependencies = []
        for name in ('.micros', '.sdk'):
            dependency = root / name
            if dependency.is_symlink() and dependency.resolve().is_dir() and not (snapshot / name).exists():
                (snapshot / name).symlink_to(dependency.resolve(), target_is_directory=True)
                dependencies.append(str(dependency.resolve()))
        old_path = snapshot / relative
        old, old_hooks, _ = inspect(old_path) if old_path.exists() else ({}, {}, {})
    result = []
    for change in changes(old, current):
        change['category'] = 'documentation' if change['path'].endswith('.description') else 'unit' if is_unit else 'behavior'
        result.append(change)
    hook_changes = changes(old_hooks, current_hooks)
    needed = {c['path']: stubs[c['path']] for c in hook_changes if c['path'] in stubs}
    return dict(format=1, declaration=str(path), base=revision, changes=result, hooks=hook_changes,
                stubs=needed, external_dependencies=dependencies)


def display(report, json_output=False, show_stubs=False):
    if json_output:
        print(json.dumps(report, indent=2))
        return
    print(f"{report['declaration']} compared with {report['base'][:12]}")
    for change in report['changes']:
        print(f"[{change['category']}] {change['path']}: {change['before']!r} -> {change['after']!r}")
    for change in report['hooks']:
        print(f"[hook] {change['path']}: {change['before'] or '(new)'} -> {change['after'] or '(removed)'}")
    if not report['changes'] and not report['hooks']: print('No semantic changes.')
    if report['external_dependencies']: print('External SDK references use the current dependency checkout; compare SDK changes in its own repository.')
    if show_stubs:
        print('\n'.join(report['stubs'].values()) or 'No new or changed hook signatures.')
