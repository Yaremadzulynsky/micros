"""Resolve authored deployments into the existing self-contained unit recipes.

Composition is offline. It never changes enrollment, firmware, or server routes.
Relative paths belong to the file that declares them; includes never deep-merge.
"""

import copy
import json
from pathlib import Path
import re
import tempfile

from micros_tooling.config.configuration import load_project, read_toml, config_artifacts
from micros_tooling.storage.packages import require, canonical_schema, digest


def table(value, allowed, required, context):
    require(isinstance(value, dict) and required <= value.keys() <= allowed,
            f"{context}: expected {', '.join(sorted(required))}; allowed {', '.join(sorted(allowed))}")


def reference(owner, value):
    require(isinstance(value, str) and bool(value), f"{owner}: expected a file path")
    path = (owner.parent / value).resolve()
    require(path.is_file(), f"{owner}: referenced file does not exist: {path}")
    return path


def toml(document, *, comment="Generated by micros compose. Edit the source deployment and its references."):
    """Serialize our TOML data subset without another runtime dependency."""
    lines = ["# " + comment] if comment else []

    def key(value):
        return value if re.fullmatch(r"[A-Za-z0-9_-]+", value) else json.dumps(value)

    def tables(value):
        return isinstance(value, list) and bool(value) and all(isinstance(item, dict) for item in value)

    def scalar(value):
        if isinstance(value, str):
            return json.dumps(value, ensure_ascii=False)
        if type(value) is bool:
            return "true" if value else "false"
        if type(value) is int:
            return str(value)
        if isinstance(value, list):
            return "[" + ", ".join(scalar(item) for item in value) + "]"
        if isinstance(value, dict):
            return "{ " + ", ".join(f"{json.dumps(k)} = {scalar(v)}" for k, v in value.items()) + " }"
        raise ValueError(f"Unsupported TOML value: {value!r}")

    def emit(value, prefix, array=False):
        if prefix and (array or not value or any(not isinstance(v, dict) for v in value.values())):
            bracket = "[[" if array else "["
            lines.extend(["", bracket + ".".join(key(p) for p in prefix) + bracket.replace("[", "]")])
        for name, item in value.items():
            if not isinstance(item, dict) and not tables(item):
                lines.append(f"{key(name)} = {scalar(item)}")
        for name, item in value.items():
            if isinstance(item, dict):
                emit(item, [*prefix, name])
            elif tables(item):
                for entry in item:
                    emit(entry, [*prefix, name], array=True)

    emit(document, [])
    return "\n".join(lines) + "\n"


def service(manifest, *, authored=False):
    data = read_toml(manifest)
    table(data, {"service"}, {"service"}, str(manifest))
    definition = data["service"]
    # Old setup/application documents remain readable. Modern reusable service
    # definitions are resolved by the same model as standalone generation.
    if isinstance(definition.get('build'), dict) and 'api' in definition['build'] and not ({'memory', 'requirements'} & definition.keys()):
        from micros_tooling.config.declarations import contract
        normalized = contract(manifest)
        fields = {'name', 'version', 'build', 'capabilities', 'config_schema'}
        selected = {key: normalized[key] for key in fields}
        if authored:
            selected.update({key: copy.deepcopy(value) for key, value in definition.items()
                             if key in ('hardware', 'subscriptions', 'publications', 'memory', 'requirements')})
            selected['hardware'] = copy.deepcopy(normalized['hardware'])
        return dict(selected, source=str(manifest.parent))
    fields = {"name", "version", "build", "capabilities", "config_schema"}
    declarations = {"memory", "hardware", "requirements", "subscriptions", "publications"}
    table(definition, fields | declarations, fields - {"config_schema"}, str(manifest))
    # Legacy applications still supply their own bindings and budgets. Setup-only
    # declarations must not leak into the existing unit recipe or package ABI.
    selected = definition if authored else {k: v for k, v in definition.items() if k in fields}
    return dict(copy.deepcopy(selected), source=str(manifest.parent))


def application(path):
    app = read_toml(path)
    table(app, {"project", "services", "channels"}, {"services"}, str(path))
    result = copy.deepcopy(app)
    table(app["services"], set(app["services"]), set(), f"{path}: services")
    for alias, selection in app["services"].items():
        require(alias != "bridge", f"{path}: bridge is generated from deployment streams")
        table(selection, {"manifest", "memory", "config", "subscriptions", "publications"},
              {"manifest", "memory"}, f"{path}: service {alias}")
        definition = service(reference(path, selection["manifest"]))
        definition.update({key: copy.deepcopy(value) for key, value in selection.items() if key != "manifest"})
        result["services"][alias] = definition
    for channel in result.get("channels", {}).values():
        channel["schema"] = str(reference(path, channel["schema"]))
    return result


def endpoint(units, value, direction):
    require(isinstance(value, str), "Endpoint must be device.service.port")
    parts = value.split(".")
    require(len(parts) == 3 and parts[0] in units, f"Unknown endpoint: {value}")
    device, alias, port = parts
    selection = units[device]["services"].get(alias, {})
    binding = selection.get(direction, {}).get(port)
    require(binding is not None, f"{value}: expected a {direction} port")
    require(binding.get("channel") in units[device].get("channels", {}), f"{value}: unknown local channel")
    return device, binding, units[device]["channels"][binding["channel"]]


def compose(path):
    path = Path(path).resolve()
    doc = read_toml(path)
    if "setup" in doc:
        from micros_tooling.config.setup import compose_setup
        return compose_setup(path, doc)
    table(doc, {"deployment", "management", "devices", "connections", "streams"},
          {"deployment", "devices"}, str(path))
    table(doc["deployment"], {"name"}, {"name"}, "deployment")
    require(isinstance(doc["deployment"]["name"], str), "deployment.name must be text")
    require(isinstance(doc["devices"], dict) and doc["devices"], "Deployment needs devices")
    units, sources, identities = {}, {}, set()
    for alias, device in doc["devices"].items():
        require(re.fullmatch(r"[a-z][a-z0-9_]*", alias), f"Invalid device alias: {alias}")
        table(device, {"id", "board", "application"}, {"id", "board", "application"}, alias)
        identity = device["id"]
        require(isinstance(identity, str) and re.fullmatch(r"[0-9a-f]{12}", identity), f"{alias}: invalid hardware ID")
        require(identity not in identities, f"Hardware ID selected twice: {identity}")
        identities.add(identity)
        board_path = reference(path, device["board"])
        board = read_toml(board_path)
        table(board, {"board"}, {"board"}, str(board_path))
        app_path = reference(path, device["application"])
        unit = application(app_path)
        unit.update(unit={"device_id": identity}, board=board["board"])
        if "management" in doc:
            unit["management"] = copy.deepcopy(doc["management"])
        units[alias] = unit
        sources[alias] = {"board": str(board_path), "application": str(app_path)}

    return finish(doc, units, sources)


def finish(doc, units, sources):
    """Validate and lower shared capture/routing machinery for both authoring forms."""
    devices = {alias: {"project": f"units/{unit['unit']['device_id']}.toml"}
               for alias, unit in units.items()}

    streams = doc.get("streams", {})
    require(isinstance(streams, dict), "streams must be named tables")
    for name, stream in streams.items():
        table(stream, {"from"}, {"from"}, f"stream {name}")
        require(re.fullmatch(r"[a-z][a-z0-9_]*", name), f"Invalid stream name: {name}")
        device, binding, channel = endpoint(units, stream["from"], "publications")
        require(binding.get("kind") is None, f"{name}: capture requires an ordinary channel, not a coordination port")
        unit = units[device]
        if "bridge" not in unit["services"]:
            bridge = service(Path(__file__).resolve().parents[3] / "services/network-bridge/service.toml")
            bridge.update(memory={"arena": "RAM", "stack_bytes": 2048}, subscriptions={})
            unit["services"]["bridge"] = bridge
        else:
            require(unit["services"]["bridge"]["name"] == "board.network-bridge",
                    f"{device}: service alias bridge is reserved for network capture")
        unit["services"]["bridge"]["subscriptions"][name] = {"channel": binding["channel"]}

    routes, used, names = [], set(), set()
    connections = doc.get("connections", [])
    require(isinstance(connections, list) and len(connections) <= 8, "At most eight connections are supported")
    for route in connections:
        table(route, {"name", "from", "to", "drop_first"}, {"name", "from", "to"}, "connection")
        require(isinstance(route["name"], str) and route["name"] and route["name"] not in names,
                "Connection names must be nonempty and unique")
        names.add(route["name"])
        drop = route.get("drop_first", 0)
        require(type(drop) is int and 0 <= drop <= 100, "drop_first must be an integer from 0 to 100")
        contracts = []
        for key, direction in (("from", "publications"), ("to", "subscriptions")):
            device, binding, channel = endpoint(units, route[key], direction)
            # Router admission is per physical channel, even when two ports alias it.
            physical = (device, channel["key"])
            require(physical not in used, f"{route[key]}: channel already connected; network fan-out is unsupported")
            used.add(physical)
            require(binding.get("kind") in ("state", "action", "event"), f"{route[key]}: connection needs a coordination kind")
            contracts.append((binding["kind"], digest(canonical_schema(Path(channel["schema"]).read_bytes())),
                              channel["interface"], channel["major"], channel["minor"], channel["max_payload"]))
        require(contracts[0] == contracts[1], f"{route['name']}: endpoint contracts differ")
        routes.append(dict(name=route["name"], source=route["from"], target=route["to"], drop_first=drop))

    # Use the production recipe loader before producing any output. Paths have
    # already been made absolute, so validation does not depend on the output dir.
    with tempfile.TemporaryDirectory(prefix="micros-compose-") as temporary:
        for alias, unit in units.items():
            target = Path(temporary) / (unit["unit"]["device_id"] + ".toml")
            target.write_text(toml(unit))
            resolved = load_project(target)
            for selected in resolved["services"]:
                for source in selected["sources"]:
                    require(Path(source).is_file(), f"{alias}: missing service source: {source}")
                if "_configuration" in selected:
                    config = selected["_configuration"]
                    config_artifacts(config["name"], config["definition"], config["values"])
    return dict(name=doc["deployment"]["name"], units=units, sources=sources,
                coordination=dict(devices=devices, routes=routes), streams=streams)


def write(result, output):
    """Publish a complete validated bundle; never overwrite an existing review."""
    output = Path(output).resolve()
    require(not output.exists(), f"Output already exists: {output}. Choose a new review directory.")
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".micros-compose-", dir=output.parent) as temporary:
        staging = Path(temporary) / "bundle"
        (staging / "units").mkdir(parents=True)
        for unit in result["units"].values():
            (staging / "units" / (unit["unit"]["device_id"] + ".toml")).write_text(toml(unit))
        (staging / "coordination.toml").write_text(toml(result["coordination"]))
        (staging / "composition.json").write_text(json.dumps(result, indent=2) + "\n")
        staging.rename(output)
    return output


def describe(result):
    if "setup" in result:
        from micros_tooling.config.setup import describe_setup
        return describe_setup(result)
    lines = [result["name"]]
    for alias, unit in result["units"].items():
        lines.append(f"  {alias} ({unit['unit']['device_id']}) — {unit['board']['profile']}")
        lines.append(f"    application: {result['sources'][alias]['application']}")
        lines.append(f"    board: {result['sources'][alias]['board']}")
        lines.append(f"    services: {', '.join(unit['services'])}")
    for route in result["coordination"]["routes"]:
        suffix = f" [fault injection: drop first {route['drop_first']}]" if route["drop_first"] else ""
        lines.append(f"  connect {route['source']} → {route['target']}{suffix}")
    for name, stream in result["streams"].items():
        lines.append(f"  capture {stream['from']} → network port {name}")
    return "\n".join(lines)
